async (page) => {
  const checks = [];
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const assert = (value, name) => { if (!value) throw new Error(name); checks.push(name); };
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('http://localhost:4173');
  await page.evaluate(() => document.fonts.ready);
  await page.locator('#search-input').fill('холод');
  assert(await page.locator('#search-results a').count() === 1, 'Поиск находит холодильное оборудование');
  await page.locator('#search-input').press('Enter');
  assert(await page.locator('[data-product]:visible').count() === 1, 'Поиск фильтрует результат');
  await page.locator('.reset-filter').click();
  assert(await page.locator('[data-product]:visible').count() === 3, 'Сброс восстанавливает все карточки');
  await page.locator('[data-compare="oven"]').click();
  await page.locator('[data-compare="cold"]').click();
  await page.locator('.compare-tray [data-open-compare]').click();
  assert(await page.locator('dialog').isVisible(), 'Сравнение открывает диалог');
  assert(await page.locator('dialog th').count() > 4, 'Сравнение показывает параметры');
  await page.keyboard.press('Escape');
  assert(!await page.locator('dialog').isVisible(), 'Escape закрывает диалог');
  await page.locator('[data-clear-compare]').click();
  await page.locator('[data-details="mixer"]').click();
  assert((await page.locator('#dialog-title').textContent()).includes('миксеры'), 'Открываются характеристики оборудования');
  await page.keyboard.press('Escape');
  const faq = page.locator('.faq details').nth(1);
  await faq.locator('summary').click();
  assert(await faq.getAttribute('open') !== null, 'FAQ открывает ответ');
  await faq.locator('summary').click();
  await page.locator('[name=name]').fill('Тестовый клиент');
  await page.locator('[name=contact]').fill('client@example.com');
  await page.locator('[name=task]').fill('Оборудование для кафе, Москва');
  await page.locator('[name=consent]').check();
  await page.locator('.submit-button').click();
  assert(await page.locator('.form-result').isVisible(), 'Форма готовит письмо');
  const mailto = await page.locator('.form-result a').getAttribute('href');
  assert(mailto.startsWith('mailto:info@torgpit.ru?') && decodeURIComponent(mailto).includes('client@example.com'), 'Письмо содержит данные клиента');
  await page.locator('[name=contact]').fill('не контакт');
  await page.locator('.submit-button').click();
  assert(await page.locator('[name=contact]').evaluate(node => !node.validity.valid), 'Неверный контакт отклоняется');
  await page.goto('http://localhost:4173/');
  await page.evaluate(() => document.fonts.ready);
  await page.evaluate(() => { document.activeElement.blur(); window.scrollTo({ top: 0, behavior: 'instant' }); });
  await page.screenshot({ path: 'output/playwright/desktop-top.png', animations: 'disabled' });
  await page.screenshot({ path: 'output/playwright/desktop.png', fullPage: true, animations: 'disabled' });
  for (const width of [1440, 1024, 724, 390, 360]) {
    await page.setViewportSize({ width, height: 900 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth === innerWidth), `Нет горизонтального скролла при ${width}px`);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.mobile-toggle').click();
  assert(await page.locator('#mobile-menu').isVisible(), 'Мобильное меню открывается');
  await page.locator('#mobile-menu a[href="#catalog"]').click();
  assert(!await page.locator('#mobile-menu').isVisible(), 'Мобильное меню закрывается после перехода');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert(await page.locator('.hero-art').evaluate(node => getComputedStyle(node).animationName === 'none'), 'Reduced motion отключает пространственную анимацию');
  await page.evaluate(() => { document.activeElement.blur(); window.scrollTo({ top: 0, behavior: 'instant' }); });
  await page.screenshot({ path: 'output/playwright/mobile-top.png', animations: 'disabled' });
  await page.screenshot({ path: 'output/playwright/mobile.png', fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 724, height: 2172 });
  await page.evaluate(() => { document.activeElement.blur(); window.scrollTo({ top: 0, behavior: 'instant' }); });
  await page.screenshot({ path: 'output/playwright/reference-width.png', fullPage: true, animations: 'disabled' });
  assert(await page.evaluate(() => [...document.images].every(node => node.complete && node.naturalWidth > 0)), 'Все изображения загружены');
  assert(errors.length === 0, 'Нет ошибок JavaScript');
  return { passed: checks.length, checks, errors };
}
