async (page) => {
  const checks = [];
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const check = (value, name) => { if (!value) throw new Error(name); checks.push(name); };
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://localhost:4173/');
  await page.evaluate(() => sessionStorage.clear());
  await page.reload();
  await page.locator('.mobile-search').click();
  await page.locator('#search-input').fill('холод');
  check(await page.locator('#search-results a').count()===1,'Поиск категорий находит холодильное оборудование');
  await page.locator('#search-input').press('ArrowDown');
  check(await page.locator('#search-input').getAttribute('aria-activedescendant')==='search-option-0','Клавиатура выделяет результат поиска');
  await page.locator('#search-input').press('Enter');
  check(await page.locator('[data-product]:visible').count()===1,'Поиск ведёт к правильному направлению');
  await page.locator('.reset-filter').click();
  check(await page.locator('[data-product]:visible').count()===3,'Сброс фильтра восстанавливает карточки');
  await page.locator('[data-compare="oven"]').click();
  await page.locator('[data-compare="cold"]').click();
  await page.locator('.compare-tray [data-open-compare]').click();
  check(await page.locator('.collection-list li').count()===2,'Подборка содержит выбранные направления');
  check(await page.locator('dialog table').count()===0,'Подборка не изображает сравнение разных товаров');
  await page.locator('[data-remove-selection="cold"]').click();
  check(await page.locator('.collection-list li').count()===1,'Из подборки можно удалить направление');
  await page.keyboard.press('Escape');
  check(!await page.locator('dialog').isVisible(),'Escape закрывает диалог');
  await page.locator('[name=task]').fill('Сохранить этот текст задачи');
  await page.locator('.category[data-request="Барное и кофейное"]').click();
  check(await page.locator('[name=task]').inputValue()==='Сохранить этот текст задачи','Выбор категории не стирает задачу');
  await page.locator('.format[data-venue="Пекарня и кондитерская"]').click();
  check(await page.locator('[name=venue]').inputValue()==='Пекарня и кондитерская','Формат переносится в бриф');
  check(await page.locator('[name=task]').inputValue()==='Сохранить этот текст задачи','Выбор формата сохраняет текст');
  await page.locator('[name=name]').fill('Тестовый клиент');
  await page.locator('[name=contact]').fill('client@example.com');
  await page.locator('.brief-details summary').click();
  await page.locator('[name=city]').fill('Москва');
  await page.locator('[name=power]').selectOption('380 В');
  await page.locator('[name=stage]').selectOption('Открытие заведения');
  await page.locator('[name=consent]').check();
  await page.locator('.submit-button').click();
  check(await page.locator('.form-result').isVisible(),'Форма готовит проверяемый текст запроса');
  const text=await page.locator('#request-preview').inputValue();
  check(['Москва','380 В','Пекарня','Пароконвектоматы','Барное и кофейное','Сохранить этот текст задачи'].every(x=>text.includes(x)),'Запрос содержит формат, параметры, подборку и задачу');
  const mailto=decodeURIComponent(await page.locator('#mailto-link').getAttribute('href'));
  check(mailto.startsWith('mailto:info@torgpit.ru?')&&mailto.includes('client@example.com'),'Письмо адресовано правильно и содержит контакт');
  const download=page.waitForEvent('download');
  await page.locator('[data-download-request]').click();
  check((await download).suggestedFilename()==='torgpit-request.txt','Запрос можно скачать без почтовой программы');
  await page.evaluate(()=>{Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:()=>Promise.reject(new Error('blocked'))}});});
  await page.locator('[data-copy-request]').click();
  check((await page.locator('.result-status').textContent()).includes('Ctrl+C'),'Отказ Clipboard API имеет запасной путь');
  await page.locator('[name=task]').fill('Обновлённая задача');
  check(!await page.locator('.form-result').isVisible(),'Изменение формы скрывает устаревший запрос');
  await page.locator('[name=contact]').fill('не контакт');
  await page.locator('.submit-button').click();
  check(await page.locator('[name=contact]').evaluate(n=>!n.validity.valid),'Неверный контакт отклоняется');
  await page.locator('[name=contact]').fill('client@example.com');
  await page.locator('[name=venue]').selectOption('Кофейня');
  await page.reload();
  check(await page.locator('[name=task]').inputValue()==='Обновлённая задача','Черновик переживает перезагрузку вкладки');
  check(await page.locator('[data-compare="oven"]').getAttribute('aria-pressed')==='true','Подборка переживает перезагрузку');
  check(!await page.locator('[name=consent]').isChecked(),'Согласие не проставляется автоматически');
  const checklist=page.waitForEvent('download');
  await page.locator('.preflight-intro [data-download-checklist]').click();
  check((await checklist).suggestedFilename()==='torgpit-kitchen-checklist.txt','Инженерный чек-лист скачивается');
  const faq=page.locator('.faq details').nth(1);
  await faq.locator('summary').click();
  check(await faq.getAttribute('open')!==null,'FAQ раскрывается');
  await faq.locator('summary').click();
  for(const width of [1440,1024,768,724,390,360,320]){
    await page.setViewportSize({width,height:900});
    check(await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth),'Нет горизонтального переполнения: '+width+'px');
  }
  await page.setViewportSize({width:390,height:844});
  await page.locator('.mobile-search').click();
  await page.locator('#search-input').fill('кофе');
  check((await page.locator('#search-results a').textContent()).includes('кофейное'),'Поиск работает на телефоне');
  await page.keyboard.press('Escape');
  check(await page.locator('.mobile-search').getAttribute('aria-expanded')==='false','Escape закрывает мобильный поиск');
  await page.locator('.mobile-toggle').click();
  check(await page.locator('#mobile-menu').isVisible(),'Мобильное меню открывается');
  await page.locator('[aria-controls="buyers-menu"]').click();
  await page.locator('#mobile-menu a[href="#preflight"]').click();
  check(!await page.locator('#mobile-menu').isVisible(),'Мобильное меню закрывается после перехода');
  await page.emulateMedia({reducedMotion:'reduce'});
  check(await page.locator('.hero-image').evaluate(n=>getComputedStyle(n).animationName==='none'),'Уменьшенное движение учитывается');
  check(await page.locator('.mobile-search').evaluate(n=>n.offsetWidth>=44&&n.offsetHeight>=44),'Мобильные иконки имеют цель 44×44');
  await page.evaluate(()=>sessionStorage.clear());
  await page.goto('http://localhost:4173/');
  await page.evaluate(async()=>{for(const img of document.images)img.loading='eager';await Promise.allSettled([...document.images].map(img=>img.decode()));await document.fonts.ready;});
  check(await page.evaluate(()=>[...document.images].every(n=>n.complete&&n.naturalWidth>0)),'Все самостоятельные изображения загружены');
  check(await page.evaluate(()=>[...document.images].every(n=>!n.src.includes('reference.png'))),'Скриншот больше не используется в интерфейсе');
  for(const [width,height,name]of [[1440,1000,'desktop'],[390,844,'mobile'],[724,1000,'tablet']]){
    await page.setViewportSize({width,height});
    await page.evaluate(()=>{document.activeElement.blur();window.scrollTo({top:0,behavior:'instant'});});
    await page.screenshot({path:'output/playwright/v2-'+name+'-top.png',animations:'disabled'});
    await page.screenshot({path:'output/playwright/v2-'+name+'.png',fullPage:true,animations:'disabled'});
  }
  check(errors.length===0,'Нет ошибок JavaScript');
  return {passed:checks.length,checks,errors};
}
