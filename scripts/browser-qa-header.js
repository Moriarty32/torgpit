async (page) => {
  const checks = [], errors = [];
  const check = (ok, name) => checks.push({name, passed: Boolean(ok)});
  page.on('pageerror', error => errors.push(error.message));
  page.setDefaultTimeout(5000);
  const trigger = id => page.locator('[aria-controls="' + id + '"]');
  const closed = async id => (await trigger(id).getAttribute('aria-expanded')) === 'false';
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://localhost:4173/');
  await page.evaluate(() => sessionStorage.clear());
  await page.reload();
  await page.evaluate(() => document.fonts.ready);
  const heroTop = (await page.locator('.hero').boundingBox()).y;
  await trigger('equipment-menu').click();
  check(await page.locator('#equipment-menu').isVisible(), 'Оборудование открывается по клику');
  check((await page.locator('.hero').boundingBox()).y === heroTop, 'Мегаменю не сдвигает страницу');
  check(await page.locator('#equipment-menu .menu-link').count() === 9, 'Доступны все девять направлений');
  await trigger('formats-menu').click();
  check(await closed('equipment-menu') && await page.locator('#equipment-menu').isHidden(), 'При смене раздела предыдущая панель закрывается');
  await page.keyboard.press('Escape');
  check(await trigger('formats-menu').evaluate(n => n === document.activeElement), 'Escape возвращает фокус к пункту меню');
  await trigger('equipment-menu').focus();
  await page.keyboard.press('Enter');
  await page.keyboard.press('Tab');
  check(await page.locator('#equipment-menu a').first().evaluate(n => n === document.activeElement), 'Tab переводит фокус в открытое меню');
  await page.keyboard.press('Escape');
  await trigger('equipment-menu').click();
  await page.locator('#equipment-menu [data-category="Холодильное оборудование"]').click();
  check(await page.locator('[data-product]:visible').count() === 1 && await page.locator('[data-product="cold"]').isVisible(), 'Категория ведёт к правильному оборудованию');
  await page.locator('.reset-filter').click();
  await trigger('formats-menu').click();
  await page.locator('#formats-menu [data-venue="Пекарня и кондитерская"]').click();
  check(await page.locator('[name="venue"]').inputValue() === 'Пекарня и кондитерская', 'Формат заведения передаётся в бриф');
  await trigger('buyers-menu').click();
  await page.locator('#buyers-menu [data-info="delivery"]').click();
  check(await page.locator('#detail-dialog').isVisible() && await closed('buyers-menu'), 'Условия открываются в действующем диалоге');
  await page.keyboard.press('Escape');
  check(await trigger('buyers-menu').evaluate(n => n === document.activeElement), 'После диалога фокус возвращается в навигацию');
  await trigger('buyers-menu').click();
  const download = page.waitForEvent('download');
  await page.locator('#buyers-menu [data-download-checklist]').click();
  check((await download).suggestedFilename() === 'torgpit-kitchen-checklist.txt', 'Чек-лист скачивается из меню');
  await page.keyboard.press('Escape');
  await page.locator('.mobile-search').click();
  await page.locator('#search-input').fill('холод');
  check(await page.locator('#search-results a').count() === 1, 'Раскрывающийся поиск находит категорию');
  await page.locator('#search-input').press('ArrowDown');
  await page.locator('#search-input').press('Enter');
  check(await page.locator('.mobile-search').getAttribute('aria-expanded') === 'false', 'Поиск закрывается после выбора результата');
  await page.locator('.reset-filter').click();
  await trigger('equipment-menu').click();
  await page.locator('.header-backdrop').click({position:{x:10,y:550}});
  check(await closed('equipment-menu'), 'Клик снаружи закрывает меню');
  await page.mouse.move(3,3);
  await trigger('formats-menu').hover();
  await page.waitForTimeout(100);
  check(await closed('formats-menu'), 'Краткое наведение не раскрывает меню');
  await page.waitForTimeout(240);
  check(await trigger('formats-menu').getAttribute('aria-expanded') === 'true', 'Намеренное наведение раскрывает меню после задержки');
  const formatPanel = await page.locator('#formats-menu').boundingBox();
  await page.mouse.move(formatPanel.x + 180, formatPanel.y + 40);
  await page.waitForTimeout(260);
  check(await trigger('formats-menu').getAttribute('aria-expanded') === 'true', 'Переход указателя из строки в панель сохраняет меню');
  await page.mouse.move(3,800);
  await page.waitForTimeout(380);
  check(await closed('formats-menu'), 'Меню от наведения закрывается после ухода указателя');
  await trigger('formats-menu').hover();
  await page.waitForTimeout(350);
  await page.locator('#formats-menu a').first().focus();
  await page.mouse.move(3,800);
  await page.waitForTimeout(380);
  check(await trigger('formats-menu').getAttribute('aria-expanded') === 'true', 'Фокус внутри панели защищает её от закрытия при уходе курсора');
  await page.keyboard.press('Escape');
  await trigger('equipment-menu').click();
  await page.mouse.move(3,800);
  await page.waitForTimeout(380);
  check(await trigger('equipment-menu').getAttribute('aria-expanded') === 'true', 'Открытая кликом панель остаётся закреплённой');
  await page.keyboard.press('Escape');
  for (const width of [1440,1280,1200,1199,1024,768,724,390,360,320]) {
    await page.setViewportSize({width,height:900});
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Нет переполнения на ' + width + 'px');
    if (width >= 1200) {
      const nav = await page.locator('.primary-nav').boundingBox();
      const actions = await page.locator('.header-actions').boundingBox();
      check(nav.x + nav.width <= actions.x + 1, 'Навигация помещается рядом с действиями на ' + width + 'px');
    }
  }
  await page.setViewportSize({width:390,height:844});
  await page.locator('.mobile-toggle').click();
  check(await page.locator('#mobile-menu').getAttribute('aria-modal') === 'true', 'Мобильное меню объявлено модальным');
  check(await page.locator('main').evaluate(n => n.inert), 'Фон мобильного меню недоступен для взаимодействия');
  await page.keyboard.press('Shift+Tab');
  check(await page.locator('.drawer-email').evaluate(n => n === document.activeElement), 'Фокус удерживается внутри мобильной панели');
  await trigger('equipment-menu').click();
  await trigger('formats-menu').click();
  check(await closed('equipment-menu'), 'Мобильные подразделы раскрываются по одному');
  await page.locator('#formats-menu [data-venue="Ресторан и кафе"]').click();
  check(await page.locator('[name="venue"]').inputValue() === 'Ресторан и кафе', 'Выбор формата работает на телефоне');
  check(await page.locator('#mobile-menu').isHidden() && !await page.locator('main').evaluate(n => n.inert), 'После перехода панель закрывается, фон восстанавливается');
  await page.locator('.mobile-toggle').click();
  await trigger('buyers-menu').click();
  await page.locator('#buyers-menu [data-info="service"]').click();
  await page.keyboard.press('Escape');
  check(await page.locator('.mobile-toggle').evaluate(n => n === document.activeElement), 'После условий на телефоне фокус возвращается к кнопке меню');
  await page.locator('.mobile-toggle').click();
  await page.locator('[data-drawer-search]').click();
  check(await page.locator('#search-input').evaluate(n => n === document.activeElement) && await page.locator('#mobile-menu').isHidden(), 'Поиск из мобильного меню открывает строку и переводит фокус');
  await page.locator('#search-input').fill('кофе');
  check((await page.locator('#search-results a').textContent()).includes('кофейное'), 'Мобильный поиск ищет по категориям');
  await page.keyboard.press('Escape');
  check(await page.locator('.mobile-search').evaluate(n => n === document.activeElement), 'Escape возвращает фокус к поиску');
  await page.locator('.mobile-toggle').click();
  await page.keyboard.press('Escape');
  check(await page.locator('.mobile-toggle').evaluate(n => n === document.activeElement), 'Escape закрывает мобильное меню и возвращает фокус');
  await page.locator('.mobile-toggle').click();
  await page.setViewportSize({width:1440,height:1000});
  check(!await page.locator('main').evaluate(n => n.inert) && await page.locator('#mobile-menu').getAttribute('role') === null, 'При смене экрана модальность снимается');
  await trigger('equipment-menu').click();
  await page.setViewportSize({width:390,height:844});
  check(await page.locator('#mobile-menu').isHidden(), 'При переходе на мобильную ширину навигация сворачивается');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.locator('.mobile-toggle').click();
  check(await page.locator('#mobile-menu').evaluate(n => getComputedStyle(n).animationName === 'none'), 'Учитывается настройка уменьшения движения');
  await page.keyboard.press('Escape');
  await page.emulateMedia({reducedMotion:'no-preference'});
  const noJs = await page.context().browser().newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
  const fallback = await noJs.newPage();
  await fallback.goto('http://localhost:4173/');
  check(await fallback.locator('.fallback-nav a').count() === 5 && await fallback.locator('.fallback-nav').isVisible(), 'Без JavaScript доступны ссылки на разделы');
  await noJs.close();
  await page.evaluate(() => {sessionStorage.clear(); window.scrollTo({top:0,behavior:'instant'});});
  await page.reload();
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(async () => {await document.fonts.ready; for (const i of document.images) i.loading = 'eager'; await Promise.allSettled([...document.images].map(i => i.decode()));});
  await page.screenshot({path:'output/playwright/header-desktop.png',animations:'disabled'});
  await trigger('equipment-menu').click();
  await page.locator('#equipment-menu img').evaluate(n => n.decode());
  await page.screenshot({path:'.impeccable/review/desktop.png',animations:'disabled'});
  await trigger('formats-menu').click();
  await page.locator('#formats-menu').evaluate(n => Promise.all([...n.querySelectorAll('img')].map(i => i.decode())));
  await page.screenshot({path:'output/playwright/header-formats.png',animations:'disabled'});
  await trigger('buyers-menu').click();
  await page.screenshot({path:'output/playwright/header-buyers.png',animations:'disabled'});
  await page.locator('.mobile-search').click();
  await page.screenshot({path:'output/playwright/header-search.png',animations:'disabled'});
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(() => document.activeElement.blur());
  await page.screenshot({path:'output/playwright/header-mobile.png',animations:'disabled'});
  await page.locator('.mobile-toggle').click();
  await trigger('equipment-menu').click();
  await page.screenshot({path:'.impeccable/review/mobile.png',animations:'disabled'});
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:724,height:1000});
  await page.locator('.mobile-toggle').click();
  await page.screenshot({path:'.impeccable/review/user-724.png',animations:'disabled'});
  await page.keyboard.press('Escape');
  check(errors.length === 0, 'Нет ошибок JavaScript');
  return {passed:checks.filter(c => c.passed).length, failed:checks.filter(c => !c.passed), checks, errors};
}
